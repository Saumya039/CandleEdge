"use client";
import { useSyncExternalStore } from "react";
import { TAPES, demoControl } from "@/lib/demo";

let snap = demoControl.status();
const subscribe = (fn: () => void) => demoControl.subscribe(() => { snap = demoControl.status(); fn(); });
const get = () => snap;

/** Replay controls for the recorded-simulation demo. Shown only when NEXT_PUBLIC_DEMO=1. */
export function DemoBar() {
  const d = useSyncExternalStore(subscribe, get, get);
  return (
    <section className="panel border-sim/60 p-3" data-testid="demo-bar" aria-label="Recorded demo controls">
      <div className="flex flex-wrap items-center gap-x-4 gap-y-2">
        <span className="tag text-sim border-sim/60">RECORDED SIMULATION REPLAY</span>
        <span className="text-muted">Not live. Not real prices. Generated by the app&apos;s seeded simulator; nothing here can place an order.</span>
      </div>
      <div className="mt-2 flex flex-wrap items-center gap-2">
        <button className="btn btn-primary" onClick={() => demoControl.play(!d.playing)} data-testid="demo-play">{d.playing ? "⏸ Pause" : "▶ Play"}</button>
        <label className="flex items-center gap-1 text-muted">Day
          <select className="input" value={d.tape} onChange={(e) => void demoControl.choose(Number(e.target.value))} data-testid="demo-tape">
            {TAPES.map((t) => <option key={t.id} value={t.id}>{t.label}</option>)}
          </select>
        </label>
        {[1, 3, 8].map((f) => <button key={f} className="btn" aria-pressed={d.fps === f} onClick={() => demoControl.speed(f)}>{f}×</button>)}
        <input type="range" min={0} max={Math.max(0, d.count - 1)} value={d.idx} onChange={(e) => demoControl.seek(Number(e.target.value))} aria-label="Session position" className="min-w-[160px] flex-1" data-testid="demo-scrub" />
        <span className="num text-muted">{d.loading ? "loading…" : `${d.clock} IST`}</span>
      </div>
      <p className="mt-2 text-[11px] text-muted">Tip: select the underlying whose watchlist tag is not NO TRADE to see the signal card, trade plan, premium chart and paper trade. Risk, strategy and backtest settings are read-only here.</p>
    </section>
  );
}
